package api

func (a *Server) contentRoutes() {
	m := a.Mux
	m.HandleFunc("POST /api/shares", a.auth("user", a.createShare))
	m.HandleFunc("GET /api/shares/{token}", a.business(a.shareData))
	m.HandleFunc("GET /s/{token}", a.shareHTML)
	m.HandleFunc("GET /api/notifications", a.auth("user", a.notifications))
	m.HandleFunc("POST /api/notifications/read-all", a.auth("user", a.readAllNotifications))
	m.HandleFunc("PUT /api/notifications/{id}/read", a.auth("user", a.readNotification))
	m.HandleFunc("GET /api/works", a.auth("user", a.works))
	m.HandleFunc("DELETE /api/works/{id}", a.auth("user", a.deleteWork))
	m.HandleFunc("GET /api/admin/works", a.auth("admin", a.works))
	m.HandleFunc("POST /api/admin/works", a.superAdmin(a.uploadWork))
	m.HandleFunc("PUT /api/admin/works/{id}/featured", a.superAdmin(a.setFeaturedWork))
	m.HandleFunc("GET /api/featured-works", a.featuredWorks)
	m.HandleFunc("GET /api/featured-works/{id}", a.featuredWork)
	m.HandleFunc("DELETE /api/admin/works/{id}", a.auth("admin", a.deleteWork))
	m.HandleFunc("POST /api/features/{key}/click", a.featureClick)
	m.HandleFunc("POST /api/features/{key}/use", a.auth("user", a.featureUse))
	m.HandleFunc("GET /api/admin/feature-stats", a.auth("admin", a.featureStats))
	m.HandleFunc("POST /api/templates/{id}/sample", a.auth("user", a.templateSample))
	m.HandleFunc("POST /api/cases/{name}/sample", a.auth("user", a.caseSample))
	m.HandleFunc("GET /api/my-outfits", a.auth("user", a.myOutfits))
	m.HandleFunc("POST /api/my-outfits", a.auth("user", a.addMyOutfit))
	m.HandleFunc("DELETE /api/my-outfits/{id}", a.auth("user", a.deleteMyOutfit))
	m.HandleFunc("GET /api/outfits", a.auth("user", a.outfits))
	m.HandleFunc("GET /api/outfits/random", a.auth("user", a.randomOutfit))
	m.HandleFunc("GET /api/outfits/categories", a.auth("user", a.outfitCategories))
	m.HandleFunc("POST /api/outfits/{id}/use", a.auth("user", a.useOutfit))
	m.HandleFunc("GET /api/admin/outfits", a.auth("admin", a.adminOutfits))
	m.HandleFunc("GET /api/admin/outfits/categories", a.auth("admin", a.outfitCategories))
	m.HandleFunc("POST /api/admin/outfits/defaults", a.superAdmin(a.seedOutfits))
	m.HandleFunc("PUT /api/admin/outfits/{id}", a.auth("admin", a.saveOutfit))
	m.HandleFunc("DELETE /api/admin/outfits/{id}", a.auth("admin", a.deleteRecord("outfits")))
}
